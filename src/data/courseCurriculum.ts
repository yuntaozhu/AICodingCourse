export function getCourseModuleById(moduleId: string): CourseModule | undefined {
  return COURSE_MODULES.find((m) => m.id.toLowerCase() === moduleId.toLowerCase());
}

export function getLabsForModule(moduleId: string): LabDefinition[] {
  const mod = getCourseModuleById(moduleId);
  if (!mod) return [];
  const labSet = new Set(mod.labIds);
  return COURSE_LABS.filter((lab) => labSet.has(lab.id));
}

export function getResourcesForModule(moduleCode: ModuleShortCode): CourseResource[] {
  return COURSE_RESOURCES.filter((res) => res.relatedModules.includes(moduleCode));
}
